"""Phase 5 analysis of the logged final TEST predictions (plan.md Phase 5 protocol). Reads predictions only --
no system is re-run -- and writes runs/final/REPORT.md plus copies of the predictions and reports.

    python scripts/phase5_analysis.py

Sections: retrieval per category x budget (tau 0.5) and stricter tau; abstention; paired comparisons fixed in the
protocol; answer metrics and their paired comparisons; citation integrity; descriptive error taxonomy (C-full,
B=8000); efficiency (build times, disk, latency).
"""

from __future__ import annotations

import json
import shutil
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

from isr import INDEX_DIR, RUNS_DIR
from isr.eval import evaluate as ev
from isr.eval.kit import TAU, kit_score, questions_for

FINAL = RUNS_DIR / "final"
SYSTEMS = {   # label -> predictions on test
    "BM25 two-stage (ref)": RUNS_DIR / "baselines" / "bm25-two-stage_test.json",
    "BM25 windows": RUNS_DIR / "baselines" / "bm25-windows_test.json",
    "A1d dense-only": RUNS_DIR / "A1d-dense-qwen3" / "pred_test.json",
    "A-full": RUNS_DIR / "A-full" / "pred_test.json",
    "B-full": RUNS_DIR / "B-full" / "pred_test.json",
    "C-full": RUNS_DIR / "C-full" / "pred_test.json",
}
ANSWER_SYSTEMS = {"B0 extractive": RUNS_DIR / "B0-Afull-extractive" / "pred_test.json",
                  "B-full": SYSTEMS["B-full"], "C-full": SYSTEMS["C-full"]}
BUDGETS = (2000, 8000, 32000)
REF = "BM25 two-stage (ref)"
RETRIEVAL_COMPARISONS = [(s, REF) for s in ("A1d dense-only", "A-full", "C-full")] + \
                        [("A-full", "A1d dense-only"), ("C-full", "A-full")]
ANSWER_COMPARISONS = [("B-full", "B0 extractive"), ("C-full", "B-full")]


def pct(x: float | None) -> str:
    return "–" if x is None else f"{x:.3f}"


def sig(c: dict) -> str:
    s = "**" if c["lo"] > 0 or c["hi"] < 0 else ""
    return f"{s}{c['diff']:+.3f}{s} [{c['lo']:+.3f}, {c['hi']:+.3f}]"


def main() -> int:
    qs = questions_for("test")
    cats = sorted({q["category"] for q in qs if not q["unanswerable"]})
    by_cat = {c: [q["question_id"] for q in qs if q["category"] == c] for c in cats}
    answerable = [q["question_id"] for q in qs if not q["unanswerable"]]
    unans = [q["question_id"] for q in qs if q["unanswerable"]]
    loaded = {k: ev._load(p, "test", qs) for k, p in SYSTEMS.items()}
    rows = {k: ev.question_rows(qs, v["run"]) for k, v in loaded.items()}
    reports = {k: json.loads(p.with_name(p.stem + ".report.json").read_text(encoding="utf-8")) for k, p in SYSTEMS.items()}
    out: list[str] = []
    w = out.append
    w("# Phase 5 — final test results (IndiaStatRAG test split, 352 questions)\n")
    w(f"Frozen commit tagged `phase5-frozen`; every system run once (TEST_RUNS.md). τ = {TAU} unless stated. "
      "Generated by `scripts/phase5_analysis.py` from the logged predictions. **No system was changed after these "
      "numbers were seen.**\n")
    diff = [q for q in loaded["A-full"]["run"] if loaded["B-full"]["run"][q] != loaded["A-full"]["run"][q]]
    w(f"B-full retrieval vs A-full: spans differ on {len(diff)} of {len(qs)} questions ({', '.join(diff) or '–'}). "
      "Disclosed discrepancy: the ranking is identical, but `run_b.py` hands the packer the top-300 ranked units "
      "while `run_system.py` hands it the full ranking, so the *position of the last truncated window* inside one "
      "very long provision can differ (it is centred on the best-ranked sub-unit, here beyond rank 300). Every "
      "official metric of the affected question is identical at all budgets. Not fixed (no re-runs after test). "
      "B-full is therefore not listed separately in the retrieval tables; C-full shares the same runner.\n")

    # --- retrieval tables ------------------------------------------------------------------------------
    def mean(sysk, b, qids, m):
        r = rows[sysk]["retrieval"][b]
        v = [r[i].get(m) for i in qids if r[i].get(m) is not None]
        return float(np.mean(v)) if v else None

    show = [k for k in SYSTEMS if k != "B-full"]
    for b in BUDGETS:
        w(f"\n## Evidence recall, B = {b}{' (headline)' if b == 8000 else ''}\n")
        w("| category (n) | " + " | ".join(show) + " |")
        w("|---|" + "---|" * len(show))
        for c in cats:
            w(f"| {c} ({len(by_cat[c])}) | " + " | ".join(pct(mean(k, b, by_cat[c], "evidence_recall")) for k in show) + " |")
        w("| **macro (answerable)** | " + " | ".join(
            pct(np.mean([mean(k, b, by_cat[c], "evidence_recall") for c in cats])) for k in show) + " |")
    w("\n## Other retrieval metrics at B = 8000 (macro over answerable categories)\n")
    w("| metric | " + " | ".join(show) + " |")
    w("|---|" + "---|" * len(show))
    for m in ("evidence_precision", "document_recall", "mrr"):
        w(f"| {m} | " + " | ".join(pct(np.mean([v for v in (mean(k, 8000, by_cat[c], m) for c in cats) if v is not None]))
                                    for k in show) + " |")
    w(f"| all-groups (cross_reference) | " + " | ".join(pct(mean(k, 8000, by_cat['cross_reference'], 'all_groups'))
                                                      for k in show) + " |")

    w("\n## Stricter τ, evidence recall at B = 8000 (kit `stricter_tau`)\n")
    w("| category | τ | " + " | ".join(show) + " |")
    w("|---|---|" + "---|" * len(show))
    for c in cats:
        for t in ("0.5", "0.8", "1.0"):     # structure: category -> budget -> tau -> recall
            vals = [reports[k]["official"]["retrieval"]["stricter_tau"].get(c, {}).get("8000", {}).get(t) for k in show]
            w(f"| {c} | {t} | " + " | ".join(pct(v) for v in vals) + " |")

    w("\n## Abstention (B = 8000)\n")
    w(f"{len(unans)} unanswerable / {len(answerable)} answerable test questions.\n")
    w("| system | abstention rate (unanswerable) | false abstention (answerable) |")
    w("|---|---|---|")
    for k in show:
        ab = rows[k]["abstained"]
        w(f"| {k} | {np.mean([ab[i] for i in unans]):.3f} | {np.mean([ab[i] for i in answerable]):.3f} |")

    # --- paired comparisons -----------------------------------------------------------------------------
    w("\n## Paired comparisons (protocol), Δ evidence recall at B = 8000, paired bootstrap 95% CI\n")
    w("Bold = CI excludes 0.\n")
    w("| comparison | " + " | ".join(cats) + " | answerable (all) |")
    w("|---|" + "---|" * (len(cats) + 1))
    for a, b in RETRIEVAL_COMPARISONS:
        cells = []
        for qids in [by_cat[c] for c in cats] + [answerable]:
            ra, rb = rows[a]["retrieval"][8000], rows[b]["retrieval"][8000]
            cells.append(sig(ev.paired_bootstrap([ra[i]["evidence_recall"] for i in qids],
                                                 [rb[i]["evidence_recall"] for i in qids], n_boot=5000)))
        w(f"| {a} − {b} | " + " | ".join(cells) + " |")
    ra, rb = rows["C-full"]["retrieval"][8000], rows["A-full"]["retrieval"][8000]
    x = by_cat["cross_reference"]
    c = ev.paired_bootstrap([ra[i]["all_groups"] for i in x], [rb[i]["all_groups"] for i in x], n_boot=5000)
    d = [ra[i]["all_groups"] - rb[i]["all_groups"] for i in x]
    w(f"\nC-full − A-full, cross_reference all-groups @8k: {sig(c)} (p = {c['p']:.3f}; "
      f"{sum(v > 0 for v in d)} better / {sum(v < 0 for v in d)} worse of {len(x)}).\n")
    oth = [i for i in answerable if i not in set(x)]
    for b in BUDGETS:
        d = [rows["C-full"]["retrieval"][b][i]["evidence_recall"] - rows["A-full"]["retrieval"][b][i]["evidence_recall"]
             for i in oth]
        w(f"C-full vs A-full on the {len(oth)} other answerable questions, B={b}: "
          f"{sum(v > 0 for v in d)} better / {sum(v < 0 for v in d)} worse.  ")

    # --- success criteria -------------------------------------------------------------------------------
    w("\n\n## Success criteria (plan.md §8, fixed in advance)\n")
    full = "C-full"
    beats = {c: mean(full, 8000, by_cat[c], "evidence_recall") > mean(REF, 8000, by_cat[c], "evidence_recall") for c in cats}
    sigs = {}
    for c in ("situational", "jurisdictional", "cross_reference"):
        r1, r0 = rows[full]["retrieval"][8000], rows[REF]["retrieval"][8000]
        sigs[c] = ev.paired_bootstrap([r1[i]["evidence_recall"] for i in by_cat[c]],
                                      [r0[i]["evidence_recall"] for i in by_cat[c]], n_boot=5000)["lo"] > 0
    ab = rows[full]["abstained"]
    w(f"- Full system > best BM25 in every answerable category @8k: **{all(beats.values())}** "
      f"({', '.join(f'{c}: {v}' for c, v in beats.items())})")
    w(f"- Paired-significant on situational / jurisdictional / cross_reference: "
      f"**{all(sigs.values())}** ({', '.join(f'{c}: {v}' for c, v in sigs.items())})")
    fa = float(np.mean([ab[i] for i in answerable]))
    w(f"- Abstention > 0 with false abstention ≤ ~5%: **{np.mean([ab[i] for i in unans]) > 0 and fa <= 0.05}** "
      f"(abstention {np.mean([ab[i] for i in unans]):.3f}, false {fa:.3f})")
    pr = [mean(k, 8000, by_cat[c], "evidence_precision") for k in (full, REF) for c in cats]
    w(f"- 'Good' — precision vs BM25 at 8k (macro): {np.mean(pr[:len(cats)]):.3f} vs {np.mean(pr[len(cats):]):.3f}")

    # --- answers -----------------------------------------------------------------------------------------
    w("\n## Answer metrics (official kit; answerable questions; mean over questions per category)\n")
    ans = {k: json.loads(p.read_text(encoding="utf-8"))["answers"] for k, p in ANSWER_SYSTEMS.items()}
    qmap = {q["question_id"]: q for q in qs}
    scored = {k: {i: kit_score.score_answer(qmap[i], a.get(i)) for i in answerable} for k, a in ans.items()}
    for m in ("fact_coverage", "citation_recall", "citation_precision"):
        w(f"\n**{m}**\n")
        w("| category | " + " | ".join(ANSWER_SYSTEMS) + " |")
        w("|---|" + "---|" * len(ANSWER_SYSTEMS))
        for c in cats + ["ALL"]:
            ids = answerable if c == "ALL" else by_cat[c]
            w(f"| {c} | " + " | ".join(pct(float(np.mean([scored[k][i].get(m) or 0.0 for i in ids]))) for k in ANSWER_SYSTEMS) + " |")
    w("\n(Citation precision of an answer without citations counted as 0; abstained answerable questions score 0.)\n")
    w("| comparison | fact coverage | citation recall | citation precision |")
    w("|---|---|---|---|")
    for a, b in ANSWER_COMPARISONS:
        cells = [sig(ev.paired_bootstrap([scored[a][i].get(m) or 0.0 for i in answerable],
                                         [scored[b][i].get(m) or 0.0 for i in answerable], n_boot=5000))
                 for m in ("fact_coverage", "citation_recall", "citation_precision")]
        w(f"| {a} − {b} | " + " | ".join(cells) + " |")
    for k in ANSWER_SYSTEMS:
        qq = [s.get("quotes", 0) for s in scored[k].values()]
        w(f"\n{k}: answers with ≥1 scored quote {sum(1 for v in qq if v)}/{len(answerable)}; "
          f"answered (not abstained) {sum(not scored[k][i]['abstained'] for i in answerable)}/{len(answerable)}.")
    rep = json.loads(SYSTEMS["C-full"].with_name("pred_test.report.json").read_text(encoding="utf-8"))
    qg = {c: v.get("quote_grounding") for c, v in rep["official"]["answers"]["by_category"].items()}
    w(f"\nC-full quote grounding by category (kit, over answers with quotes): {qg}\n")

    # citation integrity: every citation must be a provision that was in the packed context
    from isr.store import UnitStore
    store = UnitStore()
    keyset = set(zip(store.units["document_id"], store.units["key"]))
    for k in ("B-full", "C-full"):
        run = loaded[k]["run"]
        tot = bad_exist = bad_ctx = 0
        for i, a in ans[k].items():
            spans = run.get(i, {}).get(8000, run.get(i, {}).get("8000", []))
            docs = {s[0] if not isinstance(s, dict) else s["document_id"] for s in spans}
            for ci in a.get("citations", []):
                tot += 1
                bad_exist += (ci["document_id"], ci["key"]) not in keyset
                bad_ctx += ci["document_id"] not in docs
        w(f"- {k}: {tot} citations; cite a non-existent provision: {bad_exist}; cite a document outside the "
          f"retrieved context: {bad_ctx}")

    # --- error taxonomy (descriptive) ------------------------------------------------------------------
    w("\n## Error taxonomy — C-full, B = 8000, τ = 0.5 (descriptive; test is not used for any decision)\n")
    run = loaded["C-full"]["run"]
    norm = lambda t: " ".join(str(t).lower().replace(",", " ").split())
    tax = Counter()
    per_cat = defaultdict(Counter)
    for q in qs:
        i = q["question_id"]
        spans = run.get(i, {}).get(8000, run.get(i, {}).get("8000", []))
        spans = [tuple(s) if not isinstance(s, dict) else (s["document_id"], s["char_start"], s["char_end"]) for s in spans]
        if q["unanswerable"]:
            if spans:
                tax["missed abstention (unanswerable answered)"] += 1
                per_cat["unanswerable"]["missed abstention"] += 1
            continue
        if not spans:
            for _ in q["gold_evidence"]:
                tax["false abstention"] += 1
                per_cat[q["category"]]["false abstention"] += 1
            continue
        for g in q["gold_evidence"]:
            best, doc_hit, title_hit, key_other = 0.0, False, False, False
            gtitles = {norm(store.title(l["document_id"])) for l in g["locations"] if l["document_id"] in store.docs.index}
            gkeys = {l["key"] for l in g["locations"]}
            for l in g["locations"]:
                L = l["char_end"] - l["char_start"]
                ov = sum(max(0, min(e, l["char_end"]) - max(s, l["char_start"])) for d, s, e in spans if d == l["document_id"])
                best = max(best, ov / max(1, L))
                doc_hit |= any(d == l["document_id"] for d, _, _ in spans)
            for d, s, e in spans:
                if d in store.docs.index and norm(store.title(d)) in gtitles:
                    title_hit = True
                for u in store.doc_units(d):
                    if store.kind[u] == "provision" and store.start[u] < e and store.end[u] > s and \
                            store.units.at[u, "key"] in gkeys and not any(d == l["document_id"] for l in g["locations"]):
                        key_other = True
                        break
            if best >= TAU:
                label = "found"
            elif best > 0:
                label = "partial coverage (< τ)"
            elif doc_hit or title_hit:
                label = "right Act, wrong provision"
            elif key_other:
                label = "right provision number, other Act/copy (wrong jurisdiction or instrument)"
            else:
                label = "wrong Act (gold Act not in context)"
            tax[label] += 1
            per_cat[q["category"]][label] += 1
    labels = ["found", "partial coverage (< τ)", "right Act, wrong provision",
              "right provision number, other Act/copy (wrong jurisdiction or instrument)",
              "wrong Act (gold Act not in context)", "false abstention"]
    w("Unit = gold evidence group. 'found' = covered ≥ τ by the returned spans.\n")
    w("| category | " + " | ".join(labels) + " |")
    w("|---|" + "---|" * len(labels))
    for c in cats:
        w(f"| {c} | " + " | ".join(str(per_cat[c][l]) for l in labels) + " |")
    w(f"| **all** | " + " | ".join(str(tax[l]) for l in labels) + " |")
    w(f"\nMissed abstentions (unanswerable questions given spans): {tax['missed abstention (unanswerable answered)']} "
      f"of {len(unans)}. Budget wasted on duplicate copies: 0 by construction (packer emits one unit per dedup class).\n")
    tr = json.loads((RUNS_DIR / "C-full" / "trace_test.json").read_text(encoding="utf-8"))
    reasons = Counter(tr[i]["abstain_reason"] or "MISSED" for i in unans)
    w(f"Abstention reasons on the {len(unans)} unanswerable test questions: {dict(reasons)}.\n")
    w("| missed unanswerable question | CE top score |")
    w("|---|---|")
    for i in unans:
        if not tr[i]["abstain_reason"]:
            w(f"| {i}: {qmap[i]['question']} | {tr[i]['rerank_top']:.3f} |")
    w("\nAll missed abstentions are foreign law or case law — question types barely present among dev's "
      "unanswerables (dominated by real Act + non-existent section, which the rules catch: 16/16 here). The rules "
      "recognise Indian statute titles only; 'Companies Act' in the UK question even resolved to the Indian Act. "
      "This is the residual risk recorded in the Phase 2 overfitting audit.\n")

    # --- efficiency --------------------------------------------------------------------------------------
    w("\n## Efficiency\n")
    def size(p: Path) -> float:
        return sum(f.stat().st_size for f in p.rglob("*") if f.is_file()) / 1e9 if p.exists() else 0.0
    w("| index | build time | disk |")
    w("|---|---|---|")
    for name, d, key in (("BM25 over units", INDEX_DIR / "bm25_units", "params.json"),
                         ("dense (Qwen3-Embedding-0.6B)", INDEX_DIR / "dense_qwen3-0.6b", "info.json"),
                         ("Act cards (Plan C, built; not used by C-full)", INDEX_DIR / "acts", "info.json"),
                         ("xref graph (Plan C)", INDEX_DIR / "xref", "info.json")):
        info = json.loads((d / key).read_text(encoding="utf-8")) if (d / key).exists() else {}
        t = info.get("seconds") or (info.get("minutes", 0) * 60)
        w(f"| {name} | {t / 60:.1f} min | {size(d):.2f} GB |")
    w("\n| system | test wall time (352 Q) | per question |")
    w("|---|---|---|")
    for k in ("A1d dense-only", "A-full", "B-full", "C-full"):
        meta = json.loads(SYSTEMS[k].read_text(encoding="utf-8")).get("meta", {})
        secs = meta.get("seconds")
        if secs is None and "timing" in meta:
            secs = sum(v for kk, v in meta["timing"].items() if kk.endswith("_s"))
        w(f"| {k} | {secs / 60:.1f} min | {secs / len(qs):.2f} s |" if secs else f"| {k} | – | – |")
    w("\nTimes include model loading; B/C answer time uses the LLM cache for questions whose context was "
      "already answered by an earlier system in the same session (C-full reuses B-full's answers where its "
      "context is identical).\n")

    FINAL.mkdir(parents=True, exist_ok=True)
    (FINAL / "REPORT.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    for k, p in {**SYSTEMS, **ANSWER_SYSTEMS}.items():
        dst = FINAL / p.parent.name
        dst.mkdir(exist_ok=True)
        for f in (p, p.with_name(p.stem + ".report.json")):
            if f.exists():
                shutil.copy2(f, dst / f.name)
    print(f"wrote {FINAL / 'REPORT.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
